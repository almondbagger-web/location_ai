COMMA_NUM_RE = re.compile(r"(?<![\d.])\d{1,4}(?:\s*[,、，]\s*\d{1,4})+(?![\d.])")
RANGE_NUM_RE = re.compile(r"(?<![\d.])\d{1,3}\s*[-–—~～〜－]\s*\d{1,3}(?![\d月年日時分丁目番地号])")
