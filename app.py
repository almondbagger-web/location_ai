    compact = re.sub(r"\s+", "", name)
    if compact in {"学校", "小学校", "中学校", "高校", "大学", "高等学校"}:
        return False
    if not any(term in name for term in SCHOOL_TERMS):
        return False
    if any(term in name for term in ("公園", "道路", "通り", "交差点", "歩道橋")):
        return False
    return True


