def absorb_new_location(reply: str, allow_save: bool) -> str:
    match = re.search(r"\[\[NEW_LOCATION:\s*(\{.*?\})\s*\]\]", reply, flags=re.S)
    if not match:
        return reply
    if allow_save:
        try:
            data = json.loads(match.group(1))
            save_new_location(
                data.get("title", ""),
                "",
                data.get("address", ""),
                data.get("description", ""),
            )
        except Exception:
            pass
    return reply.replace(match.group(0), "")


